import { readFileSync, writeFileSync } from 'node:fs';
const path = 'supabase/migrations/20260906050000_learning_value.sql';
const tuning = JSON.stringify(JSON.parse(readFileSync('supabase/functions/_shared/learning-value-tuning.json', 'utf8')));
const sql = readFileSync(path, 'utf8');
const generated = sql.replace(/-- BEGIN TUNING[\s\S]*?-- END TUNING/, () => `-- BEGIN TUNING (generated by scripts/sync-learning-tuning.mjs)\nCREATE FUNCTION public.learning_value_tuning() RETURNS jsonb\nLANGUAGE sql IMMUTABLE SET search_path='' AS $$ SELECT '${tuning}'::jsonb $$;\n-- END TUNING`);
if (process.argv.includes('--check')) {
  if (sql !== generated) throw new Error('SQL tuning differs from the shared tuning. Run node scripts/sync-learning-tuning.mjs.');
} else writeFileSync(path, generated);
