import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { isDeepStrictEqual } from 'node:util';
import { game } from './load-game.mjs';

const balance = JSON.parse(readFileSync('supabase/functions/_shared/game-balance.json', 'utf8'));
const files = readdirSync('supabase/migrations').filter(file => file.endsWith('.sql')).sort();
const sql = files.map(file => readFileSync(`supabase/migrations/${file}`, 'utf8')).join('\n');
const tuning = [...sql.matchAll(/CREATE(?: OR REPLACE)? FUNCTION public\.learning_value_tuning\(\)[\s\S]*?SELECT '([^']+)'::jsonb/g)].at(-1)?.[1];
const state = [...sql.matchAll(/(?:state jsonb DEFAULT|ALTER TABLE public\.kingdom_state ALTER COLUMN state SET DEFAULT) '([^']+)'::jsonb/g)].at(-1)?.[1];
if (!tuning || !state) throw new Error('Database balance definitions are missing.');

const initial = game.newKingdom();
const aligned = isDeepStrictEqual(JSON.parse(tuning), balance.learningValue) && isDeepStrictEqual(JSON.parse(state), initial);
if (process.argv.includes('--check')) {
  if (!aligned) throw new Error('SQL tuning differs from game-balance.json. Run node scripts/sync-game-balance.mjs.');
} else if (!aligned) {
  const latest = files.at(-1).slice(0, 14);
  const next = new Date(`${latest.slice(0, 4)}-${latest.slice(4, 6)}-${latest.slice(6, 8)}T${latest.slice(8, 10)}:${latest.slice(10, 12)}:${latest.slice(12)}Z`);
  const version = Math.max(Date.now(), next.getTime() + 1000);
  const stamp = new Date(version).toISOString().replace(/\D/g, '').slice(0, 14);
  const literal = JSON.stringify(balance.learningValue).replaceAll("'", "''");
  const kingdom = JSON.stringify(initial).replaceAll("'", "''");
  const generated = `-- Generated by scripts/sync-game-balance.mjs from game-balance.json.\n` +
    `CREATE OR REPLACE FUNCTION public.learning_value_tuning() RETURNS jsonb\n` +
    `LANGUAGE sql IMMUTABLE SET search_path='' AS $$ SELECT '${literal}'::jsonb $$;\n` +
    `ALTER TABLE public.kingdom_state ALTER COLUMN state SET DEFAULT '${kingdom}'::jsonb;\n`;
  writeFileSync(`supabase/migrations/${stamp}_game_balance.sql`, generated);
}
