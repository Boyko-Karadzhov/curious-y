import { readFileSync, writeFileSync } from 'node:fs';

const path = 'supabase/migrations/20260925120000_game_balance.sql';
const balance = JSON.parse(readFileSync('supabase/functions/_shared/game-balance.json', 'utf8'));
const previous = readFileSync('supabase/migrations/20260923190000_offline_economy.sql', 'utf8');
const initial = JSON.parse(previous.match(/ALTER TABLE public\.kingdom_state ALTER COLUMN state SET DEFAULT '([^']+)'::jsonb;/)?.[1] ?? 'null');
if (!initial) throw new Error('Kingdom state template is missing.');
initial.food = balance.recruitment.cost * balance.economy.startingFoodPacks;
initial.metal = balance.forge.resourceCost * balance.economy.startingMetalForges;
const literal = JSON.stringify(balance.learningValue).replaceAll("'", "''");
const state = JSON.stringify(initial).replaceAll("'", "''");
const generated = `-- Generated by scripts/sync-game-balance.mjs from game-balance.json.\n` +
  `CREATE OR REPLACE FUNCTION public.learning_value_tuning() RETURNS jsonb\n` +
  `LANGUAGE sql IMMUTABLE SET search_path='' AS $$ SELECT '${literal}'::jsonb $$;\n` +
  `ALTER TABLE public.kingdom_state ALTER COLUMN state SET DEFAULT '${state}'::jsonb;\n`;

if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== generated) throw new Error('SQL tuning differs from game-balance.json. Run node scripts/sync-game-balance.mjs.');
} else writeFileSync(path, generated);
